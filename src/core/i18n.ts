export const I18N: Record<string, Dict> = {};
for (const l of UI_LANGS) I18N[l] = { ...CORE[l], ...EXTRA[l], ...DIALOGS[l] };

/** Machine-translated strings for interface languages without a hand-made translation. */
const MACHINE: Record<string, Dict> = {};

export function setMachineStrings(lang: string, dict: Dict | null): void {
  if (dict) MACHINE[lang] = dict;
  else delete MACHINE[lang];
}

export function getMachineStrings(lang: string): Dict | null {
  return MACHINE[lang] || null;
}

export function hasMachineStrings(lang: string): boolean {
  return !!MACHINE[lang];
}

/** True for the seven languages translated by hand (and English itself). */
export function isHandTranslated(lang: string): boolean {
  return (UI_LANGS as readonly string[]).includes(lang);
}

/** Interface code for a language: hand-made translation if one exists for its base language, else the code itself (machine). */
export function uiCodeFor(code: string | null | undefined): string {
  if (!code || code === "auto") return "en";
  const b = baseLang(code);
  return (UI_LANGS as readonly string[]).includes(b) ? b : code;
}

/** Interface language for a setting: explicit code, or "auto" → the translation language. Any language works. */
export function resolveUiLang(uiSetting: string | null | undefined, targetLang: string): string {
  if (uiSetting && uiSetting !== "auto") return uiCodeFor(uiSetting);
  return uiCodeFor(targetLang);
}

const RTL = new Set(["ar", "he", "iw", "fa", "fa-AF", "ur", "ps", "sd", "ug", "yi", "dv", "ckb", "pa-Arab", "ms-Arab", "bal"]);
export function isRtl(lang: string): boolean {
  return RTL.has(lang);
}

/** The English interface strings — the source for machine translation. */
export function englishStrings(): Dict {
  return { ...I18N.en };
}

export function translate(lang: string, key: string, vars?: Record<string, string | number>): string {
  let s = I18N[lang]?.[key] ?? MACHINE[lang]?.[key] ?? I18N.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export type TFunc = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: string): TFunc {
  return (key, vars) => translate(lang, key, vars);
}
